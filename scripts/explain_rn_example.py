"""Explain the BP rows of Ramachandra-Natarajan Example 3.2 (arXiv:2006.00516 v6, n = 12).

    python -m scripts.explain_rn_example

R-N report, numerically, that the unordered Boros-Prekopa (BP) bound equals the tight
bound for k = 1..4, 7, 8 and that their ordered BP bound (Theorem 3.1(b)) equals it for
k = 1..4, 7, 8, 9, 12. For each k this script decides exactness with the criteria of
notes/proofs/exactness.md and backs every verdict by an exact certificate:
  * "exact"     : an exact pairwise independent law on {0,1}^12 (Fractions, checked by
                  general.verify_law) attaining the bound; its support is suggested by
                  HiGHS and the law is then solved and checked exactly;
  * "not exact" : an exact violation of a necessary condition (E1-E4; for the ordered
                  bound via E5, which reduces it to the n - r smallest marginals).
Writes results/exactness/rn_example_3_2.md.
"""
from fractions import Fraction
from pathlib import Path

from pwbound import general as G

REPO = Path(__file__).resolve().parents[1]
P = [Fraction(s) for s in ("0.0651", "0.0977", "0.1220", "0.1705", "0.3046", "0.4402",
                           "0.4952", "0.6075", "0.6842", "0.8084", "0.9489", "0.9656")]
REPORTED = {  # R-N Table: (unordered BP, ordered BP, tight), as printed (4 decimals)
    1: ("1", "1", "1"), 2: ("1", "1", "1"), 3: ("1", "1", "1"), 4: ("1", "1", "1"),
    5: ("1", "1", "0.9957"), 6: ("0.9497", "0.9254", "0.8931"), 7: ("0.5018", "0.5018", "0.5018"),
    8: ("0.2509", "0.2509", "0.2509"), 9: ("0.1326", "0.1290", "0.1290"),
    10: ("0.0795", "0.0712", "0.0692"), 11: ("0.0530", "0.0249", "0.0230"),
    12: ("0.0379", "0.0064", "0.0064")}


def exact_attaining_law(p, k, bound, layers=None):
    """Exact law with marginals p, pairwise independent, P(S >= k) = bound (or None)."""
    flt = (lambda x: sum(x) in layers) if layers is not None else None
    value, law = G.float_tight(p, k, states_filter=flt)
    if value is None or abs(value - float(bound)) > 1e-9:
        return None
    exact = G.solve_exact_on_support(p, sorted(law))
    if exact is None or min(exact.values()) < 0:
        return None
    return exact if G.tail(G.verify_law(p, exact), k) == bound else None


def bp_verdict(p, k):
    """(value, verdict, reason): necessary conditions from general.bp_exactness_verdict;
    an "open" verdict is turned into "exact" only by an exact law (see analyse)."""
    bp, verdict, reason = G.bp_exactness_verdict(p, k)
    return bp, ("exact?" if verdict == "open" else verdict), reason


def analyse(k):
    n = len(P)
    ps = sorted(P)
    row = {"k": k}
    float_value, _ = G.float_tight(P, k)
    row["tight"] = float_value
    # unordered
    bp, verdict, reason = bp_verdict(P, k)
    if verdict == "exact?":
        layers = None if bp == 1 else sorted(G.bp_optimum(n, k, *G.moments(P))[1][0])
        law = exact_attaining_law(P, k, bp, layers=set(range(k, n + 1)) if bp == 1 else set(layers))
        verdict = "exact" if law else "?"
        reason += f"; exact law with {len(law)} atoms" if law else "; no exact law found"
    row["unordered"] = (bp, verdict, reason)
    # ordered (Theorem 3.1(b)): min over r of BP on the n-r smallest with threshold k-r
    terms = []
    for r in range(k):
        sub = ps[: n - r]
        val = G.bp_optimum(n - r, k - r, *G.moments(sub))[0]
        terms.append((val, r))
    obp = min(v for v, _ in terms)
    argmins = [r for v, r in terms if v == obp]
    law = exact_attaining_law(P, k, obp)
    if law:
        row["ordered"] = (obp, "exact", f"r* = {argmins}; exact law with {len(law)} atoms")
    elif obp == 1:
        # an exact bound of 1 means S >= k a.s. for the full vector: E1 on all n marginals
        _, v, why = bp_verdict(P, k)
        row["ordered"] = (obp, v if v == "not exact" else "?", "bound 1, so " + why)
    else:
        # E5: ordered exact forces the sub-BP at every minimising r to be exact for the
        # n - r smallest marginals; refute that for each minimiser
        reasons = []
        for r in argmins:
            _, v, why = bp_verdict(ps[: n - r], k - r)
            reasons.append((r, v, why))
        ok = all(v == "not exact" for _, v, _ in reasons)
        row["ordered"] = (obp, "not exact" if ok else "?",
                          "E5 via r* = " + "; ".join(f"{r}: {why}" for r, _, why in reasons))
    return row


def main():
    rows = [analyse(k) for k in range(1, len(P) + 1)]
    fmtv = lambda v: "1" if v == 1 else f"{float(v):.5f}"
    lines = ["# Ramachandra–Natarajan Example 3.2 (n = 12): why the BP bounds are exact or not",
             "",
             "_Generated by `python -m scripts.explain_rn_example`. Do not edit by hand._",
             "",
             "Marginals p = (" + ", ".join(str(float(x)) for x in P) + ").",
             "Criteria E1–E5: `notes/proofs/exactness.md`. Every verdict has an exact certificate:",
             "an exact law (Fractions, checked by `general.verify_law`) or an exact violation of a",
             "necessary condition. \"tight\" is the HiGHS optimum of the 4096-state LP (float).",
             "",
             "| k | tight (HiGHS) | R–N tight | unordered BP | verdict | reason | ordered BP | verdict | reason |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        u, o = r["unordered"], r["ordered"]
        lines.append(f"| {r['k']} | {r['tight']:.5f} | {REPORTED[r['k']][2]} | {fmtv(u[0])} | {u[1]} | {u[2]} "
                     f"| {fmtv(o[0])} | {o[1]} | {o[2]} |")
    out = REPO / "results" / "exactness" / "rn_example_3_2.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    for r in rows:
        print(r["k"], "unordered:", r["unordered"][1], "| ordered:", r["ordered"][1], "|", r["ordered"][2])
    print(f"wrote {out.relative_to(REPO)}")
    return rows


if __name__ == "__main__":
    main()
