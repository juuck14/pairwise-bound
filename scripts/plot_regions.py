"""Region map of the pieces of M(p, q) on 0 <= p <= q <= 1 (figure for slides/report).

    python -m scripts.plot_regions [--n 1200]

Writes results/regions/region_map.png. Boundaries are traced from the argmin
piece evaluated in floating point on an n x n grid; the exact inequalities are
in results/regions/REGIONS.md (generated by scripts.classify and checked by the
verifier). The figure is an illustration, not evidence.
"""
import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy import ndimage

from pwbound import parametric, poly

REPO = Path(__file__).resolve().parents[1]
INK, MUTED, LINE, SURFACE, ACCENT = "#1f2328", "#59636e", "#3d444d", "#ffffff", "#0b6bcb"


def piece_labels(n):
    grid = (np.arange(n) + 0.5) / n
    pp, qq = np.meshgrid(grid, grid)          # rows: q, columns: p
    ids = [v["id"] for v in parametric.vertices()]
    values = np.stack([sum(float(c) * pp**i * qq**j for (i, j), c in v["Q"].items())
                       for v in parametric.vertices()])
    labels = np.argmin(values, axis=0)
    labels = np.where(pp <= qq, labels, -1)   # outside the domain
    return grid, labels, ids


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--n", type=int, default=1200)
    args = parser.parse_args(argv)
    grid, labels, ids = piece_labels(args.n)
    active = sorted({int(k) for k in np.unique(labels) if k >= 0})

    fig, ax = plt.subplots(figsize=(7.2, 7.2), dpi=150)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    extent = (0, 1, 0, 1)
    # M = 1 region gets a light tint: it is the one piece with a qualitative meaning
    m_one = ids.index("V18")
    ax.imshow(np.where(labels == m_one, 1.0, np.nan), origin="lower", extent=extent,
              cmap=matplotlib.colors.ListedColormap(["#dde9f7"]), vmin=0, vmax=1, interpolation="nearest")
    for k in active:
        ax.contour(grid, grid, (labels == k).astype(float), levels=[0.5], colors=LINE, linewidths=0.9)
    ax.plot([0, 1], [0, 1], color=INK, linewidth=1.4)          # p = q edge of the domain
    ax.plot([0, 0], [0, 1], color=INK, linewidth=1.4)
    ax.plot([0, 1], [1, 1], color=INK, linewidth=1.4)

    marker = (0.4, 0.6)
    for k in active:
        # pad so that the array border counts as a region boundary
        dist = ndimage.distance_transform_edt(np.pad(labels == k, 1))[1:-1, 1:-1]
        far_from_marker = np.hypot(grid[None, :] - marker[0], grid[:, None] - marker[1]) > 0.06
        r, c = np.unravel_index(np.argmax(dist * far_from_marker), dist.shape)
        size = 9 if dist[r, c] > 25 else 7
        ax.text(grid[c], grid[r], ids[k], ha="center", va="center", fontsize=size, color=INK)

    ax.plot([marker[0]], [marker[1]], marker="o", markersize=6, color=ACCENT,
            markeredgecolor=SURFACE, markeredgewidth=1.5)
    ax.annotate("(2/5, 3/5): M = 61/75 (piece V12)", xy=marker, xytext=(0.56, 0.22), fontsize=8,
                color=INK, arrowprops=dict(arrowstyle="-", color=MUTED, linewidth=0.8))
    ax.text(0.80, 0.93, "M = 1", fontsize=8, color=MUTED, ha="center")

    ax.set_xlim(-0.01, 1.01)
    ax.set_ylim(-0.01, 1.01)
    ax.set_aspect("equal")
    ax.set_xlabel("p  (P(X1)=P(X2)=p)", color=INK)
    ax.set_ylabel("q  (P(X3)=P(X4)=P(X5)=q)", color=INK)
    for spine in ("top", "right"):
        ax.spines[spine].set_visible(False)
    for spine in ("left", "bottom"):
        ax.spines[spine].set_color(MUTED)
    ax.tick_params(colors=MUTED)
    ax.set_title("Pieces of M(p,q) = max P(X1+...+X5 >= 3) on 0 <= p <= q <= 1",
                 fontsize=10, color=INK, loc="left")
    fig.text(0.01, 0.01, "11 pieces; formulas and exact inequalities: results/regions/REGIONS.md. "
             "Boundaries traced on a grid (illustration).", fontsize=7, color=MUTED)
    out = REPO / "results" / "regions" / "region_map.png"
    fig.savefig(out, bbox_inches="tight", facecolor=SURFACE)
    print(f"wrote {out.relative_to(REPO)}")


if __name__ == "__main__":
    main()
